package com.saidjte.schoolradio.core.util

/**
 * قرار ما بعد نغمة الإعلان (v0.50.0) — منطق صافٍ بلا أي تبعيات أندرويد
 * (نفس فلسفة BroadcastToneLogic) ليبقى قابلاً للاختبار وحدوياً بلا جهاز.
 *
 * الإعلان لم يعد نغمة فحسب: نغمة ثم شارة «مباشر» في الصفحة الرئيسية ثم
 * نشيد الافتتاح المختار من المكتبة آلياً. هذا الكائن يحسم «ماذا يحدث بعد
 * النغمة» بمعزل عن مكان التنفيذ — قرار واحد حتمي من ثلاث حقائق مصدرية:
 * هل المدرسة اختارت نشيداً؟ هل ما زال في المكتبة؟ هل ملفه متوفر على الجهاز؟
 */
object OpeningAnthemLogic {

    /** قرار ما بعد النغمة */
    sealed interface Decision {
        /** شغّل النشيد بهذا المعرف — قائمة بعنصر واحد (نمط التشغيل الفردي v0.48.0) */
        data class Play(val trackId: Long) : Decision

        /**
         * لا نشيد بعد النغمة — والسبب رسالة صادقة للمستخدم.
         * null = لا نشيد محفوظ أصلاً (النغمة وحدها هي الإعلان، بلا رسالة).
         */
        data class Hold(val reason: String?) : Decision
    }

    /**
     * الحسم من الحقائق المصدرية — بلا قيم افتراضية ولا تخمين:
     *  - لا نشيد محفوظ: صمت بلا رسالة (سلوك v0.49.0 تماماً)
     *  - محفوظ واختفى من المكتبة: رسالة صادقة بدل صمت مريب
     *  - محفوظ وملفه مفقود: رسالة صادقة بإجراء الإصلاح (إعادة الربط)
     *  - محفوظ ومتوفر: تشغيل
     */
    fun decide(configuredId: Long?, trackExists: Boolean, isAvailable: Boolean): Decision = when {
        configuredId == null -> Decision.Hold(null)
        !trackExists -> Decision.Hold("نشيد الافتتاح المحفوظ لم يعد في المكتبة — اختر نشيداً جديداً من المكتبة")
        !isAvailable -> Decision.Hold("ملف نشيد الافتتاح غير متوفر — أعد ربطه من قائمة المقطع في المكتبة")
        else -> Decision.Play(configuredId)
    }
}
