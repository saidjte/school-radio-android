package com.saidjte.schoolradio.core.util

/**
 * v0.31.0 — منطق وضع الأداء (منطق صافٍ بلا اعتماديات أندرويد).
 *
 * الخلفية الكريستالية (هالات شعاعية كاملة الشاشة) والزجاج المتدرج وحركات Lottie
 * اللانهائية حلوة على الأجهزة القوية — لكنها على الأجهزة المتوسطة والضعيفة
 * تراكم رسم زائد يجعل التطبيق بطيئاً وساخناً. وضع الأداء يطفئ الزخارف
 * ويبقي الوظيفة كاملة: نفس الشاشات ونفس الأزرار ونفس الموجات الحية.
 *
 * القرار الأول تلقائي حسب قوة الجهاز (ذاكرة/إصدار أندرويد) مرة واحدة عند
 * أول تشغيل، ثم يبقى اختيار المستخدم حرّاً من الإعدادات.
 */
object PerformanceModeLogic {

    /** تحت هذا الحجم من الذاكرة الإجمالية يُعتبر الجهاز ضعيفاً (3GB) */
    const val LOW_RAM_THRESHOLD_MB = 3000

    /** زخارف الكريستال تحتاج إصداراً حديثاً يستطيع رسم التدرجات بسلاسة (أندرويد 8.0) */
    const val MIN_DECORATION_API = 26

    /**
     * الافتراضي التلقائي لوضع الأداء حسب قوة الجهاز.
     * مفعّل إذا: الجهاز مصنّف ضعيف الذاكرة، أو الذاكرة الإجمالية تحت 3GB،
     * أو أندرويد أقدم من 8.0 — وإلا فالوضع الكريستالي الكامل هو الافتراضي.
     */
    fun autoDefault(isLowRamDevice: Boolean, totalMemMb: Int, apiLevel: Int): Boolean =
        isLowRamDevice || totalMemMb < LOW_RAM_THRESHOLD_MB || apiLevel < MIN_DECORATION_API

    /** هل طبقة الكريستال (هالات الأورورا + الزجاج المتدرج) نشطة؟ */
    fun crystalEnabled(performanceMode: Boolean): Boolean = !performanceMode

    /** هل الحركات الزخرفية اللانهائية (Lottie/الانسياب/الهالات النابضة) نشطة؟ */
    fun animationsEnabled(performanceMode: Boolean): Boolean = !performanceMode

    /** تحويل بايتات الذاكرة إلى ميغابايت (سقف آمن ضد القسمة على صفر) */
    fun bytesToMb(bytes: Long): Int = (bytes ushr 20).toInt().coerceAtLeast(0)

    /** وصف المفتاح في الإعدادات حسب الحالة */
    fun description(enabled: Boolean): String =
        if (enabled)
            "مفعّل — واجهة مبسطة بألوان مصمتة بلا هالات أو حركات زخرفية: استجابة أسرع وبطارية أطول على الأجهزة المتواضعة. كل الوظائف تعمل كالمعتاد"
        else
            "مطفأ — الواجهة الكريستالية الكاملة بهالاتها الزجاجية وحركاتها الحية. إذا لاحظت بطئاً أو سخونة على جهازك ففعّله"
}
