package com.saidjte.schoolradio.audio

/**
 * v0.10.0 — نمطا تشغيل الميكروفون في البث المباشر:
 *
 *  - [HOLD] «استمرار للبث»: الضغط بالاستمرار يفتح الهواء، وتحرير الإصبع يغلقه.
 *    الأنسب للتدخلات الخاطفة ولعادة الاستوديو الحقيقية (PTT) — لا خطر نسيان الهواء مفتوحاً.
 *  - [TOGGLE] «ضغطة للبدء والإنهاء»: ضغطة تفتح الهواء وضغطة تالية تغلقه.
 *    الأنسب لقراءة السكربت الطويل — المذيع يتحرر من الإصبع ويتفرغ للنص.
 *
 * الافتراضي [TOGGLE] لأنه الأوفر وقتاً للمذيع القارئ، والتحويل بين النمطين
 * بضغطة واحدة من بطاقة البث نفسها — التوازن بين سيناريو الإعلان الخاطف وسيناريو القراءة الطويلة.
 */
enum class MicMode(val labelAr: String, val hintAr: String) {
    HOLD("استمرار للبث", "اضغط بالاستمرار لتبثّ — حرّر إصبعك لتنتهي"),
    TOGGLE("ضغطة للبدء", "ضغطة تفتح الهواء، وضغطة تالية تنهي البث");

    companion object {
        /** تحويل آمن من مخزن الإعدادات — أي قيمة غير معروفة تعود إلى TOGGLE */
        fun from(raw: String?): MicMode =
            entries.firstOrNull { it.name == raw } ?: TOGGLE
    }
}
